function choice(prompt, options, answer, hint, feedback, explanation, extra = {}) {
  return { type: 'choice', prompt, options, answer, hint, feedback, explanation, ...extra };
}

function judgment(prompt, correct, hint, feedback, explanation, extra = {}) {
  return { type: 'judgment', prompt, options: ['正确', '错误'], answer: correct ? 0 : 1, hint, feedback, explanation, ...extra };
}

function item(lesson, topic, question, variant) {
  return { lesson, topic, ...question, variant };
}

function round(number, title, questions) {
  const id = 'qh-' + String(number).padStart(2, '0');
  const items = questions.map((question, index) => ({
    id: id + '-' + String(index + 1).padStart(2, '0'),
    ...question,
  }));
  return { id, title, items };
}

