const judgment = (prompt, correct, hint, feedback, explanation, material, source) => ({
  type: 'judgment', prompt, options: ['正确', '错误'], answer: correct ? 0 : 1,
  hint, feedback, explanation, ...(material && { material }), ...(source && { source }),
});

const choice = (prompt, options, answer, hint, feedback, explanation, material, source) => ({
  type: 'choice', prompt, options, answer, hint, feedback, explanation,
  ...(material && { material }), ...(source && { source }),
});

const item = (number, lesson, topic, question, variant) => ({ number, lesson, topic, ...question, variant });
const round = (id, title, questions) => ({
  id, title, items: questions.map(({ number, ...question }) => ({ id: `${id}-${number}`, ...question })),
});

